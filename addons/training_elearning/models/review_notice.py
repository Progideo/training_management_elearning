"""Native delivery evidence controls revision clocks, including subsequent bounces."""

from datetime import timedelta
import logging
from odoo import api, fields, models, Command
from odoo.exceptions import AccessError, ValidationError
from .human_practical import PEDAGOGY, valid_reviewer

_logger = logging.getLogger(__name__)


class ReviewNotice(models.Model):
    _name = "training.elearning.review.notice"
    _description = "Private Practical Review Delivery"
    _inherit = ["mail.thread", "mail.activity.mixin"]
    _rec_name = "event_key"
    queue_id = fields.Many2one("training.elearning.review.queue", required=True, readonly=True, ondelete="restrict")
    company_id = fields.Many2one(related="queue_id.company_id")
    review_id = fields.Many2one("training.elearning.review", readonly=True, ondelete="restrict")
    submission_id = fields.Many2one("training.elearning.submission", required=True, readonly=True, ondelete="restrict")
    reviewer_id = fields.Many2one("res.users", readonly=True, ondelete="restrict")
    kind = fields.Selection(
        [("assignment", "Reviewer Assignment"), ("feedback", "Published Learner Feedback")],
        required=True,
        readonly=True,
    )
    event_key = fields.Char(required=True, readonly=True)
    attempt = fields.Integer(readonly=True, default=1)
    reason = fields.Text(readonly=True)
    state = fields.Selection(
        [
            ("pending", "Pending"),
            ("queued", "Queued"),
            ("sent", "Sent"),
            ("exception", "Delivery Incident"),
            ("cancelled", "Cancelled"),
        ],
        readonly=True,
        default="pending",
    )
    mail_id = fields.Many2one("mail.mail", readonly=True, ondelete="set null")
    sent_at = fields.Datetime(readonly=True)
    failed = fields.Boolean(readonly=True)
    manual_delivery = fields.Boolean(readonly=True)
    incident_activity_id = fields.Many2one("mail.activity", readonly=True, ondelete="set null")
    _one_event = models.Constraint("UNIQUE(event_key)", "This practical delivery event is already recorded.")

    @api.model_create_multi
    def create(self, vals_list):
        raise AccessError(self.env._("Practical notifications are generated by checked events."))

    def write(self, values):
        raise AccessError(self.env._("Keep practical delivery history."))

    @api.ondelete(at_uninstall=False)
    def _keep_notice(self):
        raise AccessError(self.env._("Keep practical delivery history."))

    @api.private
    def _store(self, values):
        return super(ReviewNotice, self.sudo()).write(values)

    @api.private
    def _recipient_partner(self):
        self.ensure_one()
        notice = self.sudo()
        return (
            notice.reviewer_id if notice.kind == "assignment" else notice.queue_id.membership_id.learning_user_id
        ).partner_id

    @api.private
    def _allowed(self):
        self.ensure_one()
        notice, queue = self.sudo(), self.sudo().queue_id
        member = queue.membership_id
        if notice.kind == "assignment":
            return bool(
                queue.state == "pending"
                and queue.assignment_notice_id == notice
                and queue.submission_id == notice.submission_id
                and queue.reviewer_id == notice.reviewer_id
                and valid_reviewer(notice.reviewer_id, queue.company_id, member.learning_user_id)
            )
        user = member.learning_user_id
        return bool(
            notice.review_id.delivery_notice_id == notice
            and user.active
            and not user._is_public()
            and user.partner_id == member.partner_id
            and member.active
            and member.learning_state == "active"
            and member.channel_id.active
            and member.channel_id.learning_state == "published"
            and queue.company_id in user.company_ids
            and any(
                item["id"] == queue.slide_id.id and item.get("task") == queue.practical_id.id
                for item in member._learning_plan()["slides"]
            )
        )

    @api.private
    def _create_event(self, queue, kind, *, review=None, reason=None, manual=False):
        queue._lock()
        old = queue.assignment_notice_id if kind == "assignment" else review.delivery_notice_id
        attempt = (old.attempt + 1) if old else 1
        event = (
            "assignment:%s:%s:%s:%s:%s"
            % (queue.id, queue.submission_id.id, queue.reviewer_id.id, len(queue.assignment_log or []), attempt)
            if kind == "assignment"
            else "review:%s:%s" % (review.id, attempt)
        )
        notice = super(ReviewNotice, self.sudo().with_context({})).create(
            {
                "queue_id": queue.id,
                "submission_id": queue.submission_id.id if kind == "assignment" else review.submission_id.id,
                "review_id": review.id if review else False,
                "reviewer_id": queue.reviewer_id.id if kind == "assignment" else False,
                "kind": kind,
                "event_key": event,
                "attempt": attempt,
                "reason": reason,
                "manual_delivery": manual,
            }
        )
        if kind == "assignment":
            queue._store({"assignment_notice_id": notice.id})
        else:
            review._store_notice(notice)
        if manual:
            notice._sent(fields.Datetime.now())
        else:
            notice._process()
        return notice

    @api.private
    def _assignment(self, queue):
        current = queue.sudo().assignment_notice_id
        if current and current.submission_id == queue.submission_id and current.reviewer_id == queue.reviewer_id:
            return current
        return self._create_event(queue.sudo(), "assignment")

    @api.private
    def _feedback(self, review):
        if review.delivery_notice_id:
            return review.delivery_notice_id
        return self._create_event(review.sudo().queue_id, "feedback", review=review.sudo())

    @api.private
    def _incident(self):
        self.ensure_one()
        if self.incident_activity_id:
            return
        users = self.env["res.users"].sudo().search([("active", "=", True), ("company_ids", "in", self.company_id.ids)])
        users = users.filtered(lambda user: user.has_group(PEDAGOGY))
        if users:
            activity = self.sudo().activity_schedule(
                "mail.mail_activity_data_todo",
                user_id=users[:1].id,
                summary=self.env._("Resolve the practical notification incident"),
            )
            self._store({"incident_activity_id": activity.id})

    @api.private
    def _process(self):
        for notice in self:
            notice.lock_for_update()
            notice.invalidate_recordset()
            if notice.state != "pending":
                continue
            if not notice._allowed():
                notice._store({"state": "cancelled"})
                continue
            try:
                with self.env.cr.savepoint():
                    template = (
                        "training_elearning.practical_assignment_notice"
                        if notice.kind == "assignment"
                        else "training_elearning.practical_feedback_notice"
                    )
                    mail = (
                        self.env.ref(template)
                        .sudo()
                        .send_mail(
                            notice.id,
                            force_send=False,
                            email_values={
                                "recipient_ids": [Command.set(notice._recipient_partner().ids)],
                                "email_to": False,
                                "email_cc": False,
                                "attachment_ids": [Command.clear()],
                            },
                        )
                    )
                    if not mail:
                        raise ValidationError(self.env._("The practical notification was not queued."))
                    notice._store({"mail_id": mail, "state": "queued"})
            except Exception:  # Access and human judgements survive native mail preparation failures.
                _logger.exception("Could not queue practical notice %s", notice.id)
                notice._store({"state": "exception", "failed": True})
                notice._incident()

    @api.private
    def _sent(self, at):
        self.ensure_one()
        self._store({"state": "sent", "sent_at": at})
        if self.kind != "feedback":
            return
        review, queue = self.review_id, self.queue_id
        if queue.review_id != review or queue.state == "pending":
            return
        if review.outcome == "revision" and review.revision_eligible:
            item = next(
                item for item in queue.membership_id._learning_plan()["slides"] if item["id"] == queue.slide_id.id
            )
            queue._store({"state": "revision", "revision_until": at + timedelta(days=item.get("revision_days", 14))})
            self.env["training.elearning.reminder"]._schedule_queue(queue)
        elif review.outcome == "revision" and queue.state == "delivery":
            queue._store({"state": "closed"})

    @api.private
    def _sync(self):
        for notice in self:
            if notice.state in ("cancelled", "pending") or notice.manual_delivery:
                continue
            mail = notice.sudo().mail_id
            failures = (
                self.env["mail.notification"]
                .sudo()
                .search_count(
                    [
                        "|",
                        ("mail_mail_id", "=", mail.id),
                        ("mail_message_id", "=", mail.mail_message_id.id),
                        ("notification_status", "in", ("bounce", "exception", "canceled")),
                    ]
                )
                if mail
                else 0
            )
            if notice.failed or not mail or mail.state in ("exception", "cancel") or failures:
                notice._store({"state": "exception", "failed": True})
                if notice.kind == "feedback" and notice.review_id.delivery_notice_id == notice:
                    queue = notice.queue_id
                    if (
                        queue.review_id == notice.review_id
                        and queue.state == "closed"
                        and notice.review_id.outcome == "revision"
                    ):
                        queue._store({"state": "revision" if notice.review_id.revision_eligible else "delivery"})
                notice._incident()
            elif mail.state == "sent" and notice.state != "sent":
                notice._sent(fields.Datetime.now())

    def action_resolve(self):
        self.ensure_one()
        self.queue_id._authorize()
        if not self.env.user.has_group(PEDAGOGY):
            raise AccessError(self.env._("Pedagogical coordination permission is required."))
        return {
            "type": "ir.actions.act_window",
            "res_model": "training.elearning.review.delivery",
            "view_mode": "form",
            "target": "new",
            "context": {"default_notice_id": self.id},
        }

    def action_retry(self, reason=None, manual=False):
        self.ensure_one()
        self.queue_id._authorize()
        if not self.env.user.has_group(PEDAGOGY) or not (reason or "").strip():
            raise AccessError(
                self.env._("Pedagogical coordination must record the resolution or agreed delivery channel.")
            )
        self.queue_id._lock()
        current = self.queue_id.assignment_notice_id if self.kind == "assignment" else self.review_id.delivery_notice_id
        if current != self or (not manual and self.state != "exception") or not self._allowed():
            raise ValidationError(self.env._("Resolve the current authorized notification incident."))
        if manual and self.kind != "feedback":
            raise ValidationError(self.env._("Record an agreed alternative channel only for learner feedback."))
        return self._create_event(
            self.queue_id.sudo(),
            self.kind,
            review=self.review_id.sudo() if self.review_id else None,
            reason=reason.strip(),
            manual=bool(manual),
        ).id

    @api.model
    def _cron_review_notifications(self):
        notices = self.sudo().search([("state", "in", ("pending", "queued"))], limit=100)
        notices._process()
        notices._sync()


class Queue(models.Model):
    _inherit = "training.elearning.review.queue"
    assignment_notice_id = fields.Many2one("training.elearning.review.notice", readonly=True, ondelete="restrict")


class Mail(models.Model):
    _inherit = "mail.mail"

    @api.private
    def _learning_delivery_allowed(self):
        if not super()._learning_delivery_allowed():
            return False
        notices = self.env["training.elearning.review.notice"].sudo().search([("mail_id", "=", self.id)])
        for notice in notices:
            if (
                not notice._allowed()
                or self.sudo().recipient_ids != notice._recipient_partner()
                or self.sudo().email_to
                or self.sudo().email_cc
                or self.sudo().attachment_ids
            ):
                notice._store({"state": "cancelled"})
                return False
        return True

    def _send(
        self,
        auto_commit=False,
        raise_exception=False,
        smtp_session=None,
        alias_domain_id=False,
        mail_server=False,
        post_send_callback=None,
    ):
        result = super()._send(
            auto_commit=auto_commit,
            raise_exception=raise_exception,
            smtp_session=smtp_session,
            alias_domain_id=alias_domain_id,
            mail_server=mail_server,
            post_send_callback=post_send_callback,
        )
        self.env["training.elearning.review.notice"].sudo().search([("mail_id", "in", self.ids)])._sync()
        return result


class Notification(models.Model):
    _inherit = "mail.notification"

    def write(self, values):
        result = super().write(values)
        if values.get("notification_status") in ("bounce", "exception", "canceled"):
            self.env["training.elearning.review.notice"].sudo().search(
                [
                    "|",
                    ("mail_id", "in", self.sudo().mail_mail_id.ids),
                    ("mail_id.mail_message_id", "in", self.sudo().mail_message_id.ids),
                ]
            )._sync()
        return result
