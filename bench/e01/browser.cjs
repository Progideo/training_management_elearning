const {chromium}=require('playwright');
const fs=require('node:fs'), assert=require('node:assert/strict');
(async()=>{
 const ids=JSON.parse(fs.readFileSync('evidence/e01/ids.json','utf8'));
 const password=fs.readFileSync(require('node:path').join(process.env.LMS_SECRET_DIR, 'db_password'),'utf8');
 const browser=await chromium.launch({headless:true,executablePath:chromium.executablePath()});
 const context=await browser.newContext(); const page=await context.newPage();
 const base='http://127.0.0.1:18269';
 await page.goto(base+'/web/login');
 await page.locator('[name=login]').fill('e01_browser_author');
 await page.locator('[name=password]').fill(password);
 await Promise.all([page.waitForURL(u=>!u.pathname.endsWith('/web/login')),page.locator('button[type=submit]').click()]);
 await page.goto(base+'/training/interactive/preview/'+ids.version);
 await page.locator('#status').filter({hasText:'Contenu chargé'}).waitFor();
 const frame=page.frameLocator('#content').frameLocator('iframe');
 await frame.locator('#result').filter({hasText:'portalData'}).waitFor();
 const result=JSON.parse(await frame.locator('#result').textContent());
 assert.equal(result.parentDOM,'BLOCKED');assert.equal(result.portalCookie,'BLOCKED');
 assert.equal(result.portalData,'BLOCKED');assert.equal(result.contentCookies,'');
 const launch=await page.locator('#content').getAttribute('src');
 const contentBase=launch.replace(/\/launch$/,'');
 assert.equal((await page.request.get(contentBase+'/file/private.txt')).status(),200);
 assert.equal((await page.request.get(base+new URL(contentBase).pathname+'/file/private.txt')).status(),404);
 assert.equal((await page.request.get('http://localhost:18270/web/login')).status(),404);
 assert([403,404].includes((await page.request.get(base+'/web/content?model=training.elearning.file&id='+ids.file+'&field=data')).status()));
 const oldStatus=await page.locator('#status').textContent();
 await page.evaluate(()=>window.postMessage({type:'ready',nonce:'FORGED'},location.origin));
 assert.equal(await page.locator('#status').textContent(),oldStatus);
 await page.screenshot({path:'evidence/e01/isolation.png',fullPage:true});
 fs.writeFileSync(require('node:path').join(process.env.LMS_SECRET_DIR, 'lease-url'),contentBase+'/file/private.txt');
 console.log(JSON.stringify({passed:result,checks:['isolated preview','subfile authorization','portal host refusal','content RPC/login refusal','native binary refusal','forged message ignored']}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
