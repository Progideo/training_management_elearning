"""Native mail queue with a live authorization check immediately before SMTP."""

import logging
from odoo import api, fields, models, Command
from odoo.exceptions import AccessError

_logger = logging.getLogger(__name__)


class Notice(models.Model):
    _name = "training.elearning.notice"
    _description = "Private Learning Notification"
    _inherit = ["mail.thread", "mail.activity.mixin"]
    _rec_name = "kind"
    membership_id = fields.Many2one("slide.channel.partner", required=True, ondelete="restrict", readonly=True)
    slide_id = fields.Many2one("slide.slide", required=True, ondelete="restrict", readonly=True)
    company_id = fields.Many2one(related="membership_id.channel_id.learning_company_id", store=True)
    kind = fields.Selection(
        [("withdrawal", "Activity Closed"), ("reopen", "Activity Reopened")], required=True, readonly=True
    )
    event_key = fields.Char(required=True, readonly=True, index=True)
    state = fields.Selection(
        [
            ("pending", "Pending"),
            ("queued", "Queued"),
            ("sent", "Sent"),
            ("exception", "Delivery Incident"),
            ("cancelled", "Cancelled"),
        ],
        default="pending",
        readonly=True,
    )
    mail_id = fields.Many2one("mail.mail", readonly=True, ondelete="set null")
    sent_at = fields.Datetime(readonly=True)
    incident_activity_id = fields.Many2one("mail.activity", readonly=True, ondelete="set null")
    _one_event = models.Constraint("UNIQUE(event_key)", "This notification event is already recorded.")

    @api.model_create_multi
    def create(self, vals_list):  # pylint: disable=method-required-super
        raise AccessError(self.env._("Learning notifications are generated by checked server events."))

    def write(self, vals):  # pylint: disable=method-required-super
        raise AccessError(self.env._("Keep the native notification evidence."))

    @api.ondelete(at_uninstall=False)
    def _keep_notices(self):
        raise AccessError(self.env._("Keep the notification event history."))

    @api.private
    def _store(self, values):
        return super(Notice, self.sudo()).write(values)  # pylint: disable=super-method-mismatch

    @api.private
    def _recipient_allowed(self):
        self.ensure_one()
        member, slide = self.sudo().membership_id, self.sudo().slide_id
        user = member.learning_user_id
        return bool(
            user.active
            and not user._is_public()
            and user.partner_id == member.partner_id
            and member.active
            and member.learning_state == "active"
            and member.learning_started_at
            and member.channel_id.active
            and member.channel_id.learning_company_id in user.company_ids
            and slide.channel_id == member.channel_id
            and any(item["id"] == slide.id for item in member._learning_plan()["slides"])
            and bool(slide.learning_withdrawn_at) == (self.kind == "withdrawal")
            and slide.learning_availability_event == self.event_key.split(":", 1)[0]
        )

    @api.private
    def _queue(self, member, slide, kind, event):
        slide.channel_id._learning_staff(manager=True)
        if kind not in ("withdrawal", "reopen") or member.channel_id != slide.channel_id:
            raise AccessError(self.env._("Choose the authorized learning notification context."))
        key = "%s:%s:%s" % (event, member.id, kind)
        notice = self.sudo().search([("event_key", "=", key)], limit=1)
        if not notice:
            notice = super(Notice, self.sudo().with_context({})).create(  # pylint: disable=super-method-mismatch,context-overridden
                {"membership_id": member.id, "slide_id": slide.id, "kind": kind, "event_key": key}
            )  # pylint: disable=super-method-mismatch,context-overridden
        notice._process()
        return notice

    @api.private
    def _incident(self):
        for notice in self:
            if notice.incident_activity_id:
                continue
            # Only a live coordinator in the operating company may receive the task.
            candidates = (
                self.env["res.users"]
                .sudo()
                .search([("active", "=", True), ("company_ids", "in", notice.company_id.ids)])
            )
            candidates = candidates.filtered(lambda u: u.has_group("training_elearning.group_elearning_manager"))
            coordinator = notice.create_uid if notice.create_uid in candidates else candidates[:1]
            if coordinator:
                activity = notice.sudo().activity_schedule(
                    "mail.mail_activity_data_todo",
                    user_id=coordinator.id,
                    summary=self.env._("Check the learning notification delivery"),
                )
                notice._store({"incident_activity_id": activity.id})

    @api.private
    def _process(self):
        for notice in self:
            notice.lock_for_update()
            notice.invalidate_recordset()
            if notice.state != "pending":
                continue
            if not notice._recipient_allowed():
                notice._store({"state": "cancelled"})
                continue
            try:
                with self.env.cr.savepoint():
                    mail = (
                        self.env.ref("training_elearning.activity_notice")
                        .sudo()
                        .send_mail(
                            notice.id,
                            force_send=False,
                            email_values={
                                "recipient_ids": [Command.set(notice.membership_id.learning_user_id.partner_id.ids)],
                                "email_to": False,
                                "email_cc": False,
                                "attachment_ids": [Command.clear()],
                            },
                        )
                    )
                    if not mail:
                        raise AccessError(self.env._("The native notification was not queued."))
                    notice._store({"mail_id": mail, "state": "queued"})
            except Exception:  # A delivery preparation incident never reopens a withdrawn activity.
                _logger.exception("Could not queue learning notice %s", notice.id)
                notice._store({"state": "exception"})
                notice._incident()

    @api.private
    def _sync(self):
        for notice in self.filtered(lambda row: row.state == "queued"):
            if notice.mail_id.state == "sent":
                notice._store({"state": "sent", "sent_at": notice.mail_id.write_date or fields.Datetime.now()})
            elif not notice.mail_id or notice.mail_id.state in ("exception", "cancel"):
                notice._store({"state": "exception"})
                notice._incident()

    @api.model
    def _cron_learning_notices(self):
        notices = self.sudo().search([("state", "in", ("pending", "queued"))], limit=100)
        notices._process()
        notices._sync()

    def action_retry(self):
        for notice in self:
            notice.membership_id.channel_id._learning_staff(manager=True)
            notice.lock_for_update()
            notice.invalidate_recordset()
            if notice.state != "exception":
                continue
            if notice.mail_id:
                notice.mail_id.sudo().write({"state": "outgoing", "failure_reason": False, "failure_type": False})
                notice._store({"state": "queued"})
            else:
                notice._store({"state": "pending"})
                notice._process()
        return True


class Mail(models.Model):
    _inherit = "mail.mail"

    @api.private
    def _learning_delivery_allowed(self):
        self.ensure_one()
        notice = self.env["training.elearning.notice"].sudo().search([("mail_id", "=", self.id)], limit=1)
        mail = self.sudo()
        if notice and (
            not notice._recipient_allowed()
            or mail.recipient_ids != notice.membership_id.learning_user_id.partner_id
            or mail.email_to
            or mail.email_cc
            or mail.attachment_ids
        ):
            notice._store({"state": "cancelled"})
            return False
        return True

    def _send(
        self,
        auto_commit=False,
        raise_exception=False,
        smtp_session=None,
        alias_domain_id=False,
        mail_server=False,
        post_send_callback=None,
    ):
        blocked = self.filtered(lambda mail: not mail._learning_delivery_allowed())
        if blocked:
            blocked.write({"state": "cancel"})
        result = super(Mail, self - blocked)._send(
            auto_commit=auto_commit,
            raise_exception=raise_exception,
            smtp_session=smtp_session,
            alias_domain_id=alias_domain_id,
            mail_server=mail_server,
            post_send_callback=post_send_callback,
        )
        self.env["training.elearning.notice"].sudo().search([("mail_id", "in", self.ids)])._sync()
        return result
