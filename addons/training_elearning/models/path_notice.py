# pylint: disable=super-method-mismatch,context-overridden,method-required-super
"""Private, idempotent path and course-opening notifications through native mail."""

from odoo import api, fields, models, Command
from odoo.exceptions import AccessError


class Notice(models.Model):
    _name = "training.elearning.path.notice"
    _description = "Private Curriculum Activation Notification"
    _inherit = ["mail.thread", "mail.activity.mixin"]
    _rec_name = "event_key"
    activation_id = fields.Many2one(
        "training.elearning.path.activation",
        required=True,
        readonly=True,
        ondelete="restrict",
    )
    item_id = fields.Many2one("training.elearning.path.item", readonly=True, ondelete="restrict")
    company_id = fields.Many2one(related="activation_id.company_id")
    event_key = fields.Char(required=True, readonly=True)
    state = fields.Selection(
        [
            ("pending", "Pending"),
            ("queued", "Queued"),
            ("sent", "Sent"),
            ("exception", "Delivery Incident"),
            ("cancelled", "Cancelled"),
        ],
        readonly=True,
        default="pending",
    )
    mail_id = fields.Many2one("mail.mail", readonly=True, ondelete="set null")
    sent_at = fields.Datetime(readonly=True)
    incident_activity_id = fields.Many2one("mail.activity", readonly=True, ondelete="set null")
    _one_event = models.Constraint("UNIQUE(event_key)", "This curriculum notification event is already recorded.")

    @api.model_create_multi
    def create(self, vals_list):
        raise AccessError(self.env._("Curriculum notices are generated by checked native activation events."))

    def write(self, values):
        raise AccessError(self.env._("Keep curriculum notification evidence."))

    @api.ondelete(at_uninstall=False)
    def _keep_notice(self):
        raise AccessError(self.env._("Keep curriculum notification history."))

    @api.private
    def _store(self, values):
        return super(Notice, self.sudo()).write(values)

    @api.private
    def _allowed(self):
        self.ensure_one()
        activation = self.sudo().activation_id
        registration = activation.registration_id
        user = registration.user_id
        if (
            not activation._authorized()
            or not user.active
            or user._is_public()
            or user.partner_id != registration.partner_id
            or activation.company_id not in user.company_ids
        ):
            return False
        if self.item_id:
            item = self.sudo().item_id
            member = item.membership_id
            return bool(
                item.activation_id == activation
                and item.activated_at
                and item.access_ends_at > fields.Datetime.now()
                and member.learning_state == "active"
                and member.active
                and member.channel_id.active
                and member.learning_user_id == user
                and member.learning_ends_at > fields.Datetime.now()
            )
        return True

    @api.private
    def _queue(self, activation, *, item=None):
        key = "item:%s" % item.id if item else "path:%s" % activation.id
        notice = self.sudo().search([("event_key", "=", key)], limit=1)
        if not notice:
            notice = super(Notice, self.sudo().with_context({})).create(
                {
                    "activation_id": activation.id,
                    "item_id": item.id if item else False,
                    "event_key": key,
                }
            )
        notice._process()
        return notice

    @api.private
    def _incident(self):
        self.ensure_one()
        actor = self.activation_id._coordinator()
        if actor and not self.incident_activity_id:
            activity = self.sudo().activity_schedule(
                "mail.mail_activity_data_todo",
                user_id=actor.id,
                summary=self.env._("Resolve the curriculum notification incident"),
            )
            self._store({"incident_activity_id": activity.id})

    @api.private
    def _process(self):
        for notice in self:
            notice.lock_for_update()
            notice.invalidate_recordset()
            if notice.state != "pending":
                continue
            if not notice._allowed():
                notice._store({"state": "cancelled"})
                continue
            try:
                with self.env.cr.savepoint():
                    mail = (
                        self.env.ref("training_elearning.path_activation_notice")
                        .sudo()
                        .send_mail(
                            notice.id,
                            force_send=False,
                            email_values={
                                "recipient_ids": [
                                    Command.set(notice.activation_id.registration_id.user_id.partner_id.ids)
                                ],
                                "email_to": False,
                                "email_cc": False,
                                "attachment_ids": [Command.clear()],
                            },
                        )
                    )
                    if not mail:
                        raise AccessError(self.env._("The native curriculum notification was not queued."))
                    notice._store({"state": "queued", "mail_id": mail})
            except Exception:
                notice._store({"state": "exception"})
                notice._incident()

    @api.private
    def _sync(self):
        for notice in self.filtered(lambda row: row.state == "queued"):
            if notice.mail_id.state == "sent":
                notice._store({"state": "sent", "sent_at": fields.Datetime.now()})
            elif not notice.mail_id or notice.mail_id.state in ("exception", "cancel"):
                notice._store({"state": "exception"})
                notice._incident()

    def action_retry(self):
        for notice in self:
            notice.activation_id._staff()
            notice.lock_for_update()
            notice.invalidate_recordset()
            if notice.state != "exception":
                continue
            if notice.mail_id:
                notice.mail_id.sudo().write(
                    {
                        "state": "outgoing",
                        "failure_reason": False,
                        "failure_type": False,
                    }
                )
                notice._store({"state": "queued"})
            else:
                notice._store({"state": "pending"})
                notice._process()
        return True

    @api.model
    def _cron_path_notifications(self):
        notices = self.sudo().search([("state", "in", ("pending", "queued"))], limit=100)
        notices._process()
        notices._sync()


class Mail(models.Model):
    _inherit = "mail.mail"

    @api.private
    def _learning_delivery_allowed(self):
        if not super()._learning_delivery_allowed():
            return False
        notices = self.env["training.elearning.path.notice"].sudo().search([("mail_id", "=", self.id)])
        for notice in notices:
            if (
                not notice._allowed()
                or self.sudo().recipient_ids != notice.activation_id.registration_id.user_id.partner_id
                or self.sudo().email_to
                or self.sudo().email_cc
                or self.sudo().attachment_ids
            ):
                notice._store({"state": "cancelled"})
                return False
        return True

    def _send(
        self,
        auto_commit=False,
        raise_exception=False,
        smtp_session=None,
        alias_domain_id=False,
        mail_server=False,
        post_send_callback=None,
    ):
        result = super()._send(
            auto_commit=auto_commit,
            raise_exception=raise_exception,
            smtp_session=smtp_session,
            alias_domain_id=alias_domain_id,
            mail_server=mail_server,
            post_send_callback=post_send_callback,
        )
        self.env["training.elearning.path.notice"].sudo().search([("mail_id", "in", self.ids)])._sync()
        return result
